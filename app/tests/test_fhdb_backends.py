def test_http_timeout_raises_operational_error_without_retry(monkeypatch):
    import http.client
    from fhdb import backends

    calls = 0

    class FakeConn:
        def __init__(self, host, port=None, timeout=None, **kw):
            self.sock = None

        def request(self, method, url, body=None, headers=None):
            nonlocal calls
            calls += 1

        def getresponse(self):
            raise socket.timeout("timed out")

        def close(self):
            pass

    monkeypatch.setattr(http.client, "HTTPSConnection", FakeConn)
    secret = "sb_secret_JANGAN_BOCOR"
    b = backends.HttpBackend("https://example.supabase.co", secret, timeout=0.1)
    with pytest.raises(OperationalError) as ei:
        b.execute_batch(["select 1"], "financehub_test")
    assert calls == 1   # tidak ada retry
    assert secret not in str(ei.value)


def test_http_headers_and_error_mapping(monkeypatch):
    import http.client
    import json
    from fhdb import backends

    sent = []
    responses = []

    class FakeResp:
        def __init__(self, status, body):
            self.status, self._body = status, body.encode()

        def read(self):
            return self._body

    class FakeConn:
        def __init__(self, host, port=None, timeout=None, **kw):
            self.host, self.sock = host, None

        def request(self, method, url, body=None, headers=None):
            sent.append((method, url, json.loads(body), dict(headers)))
            self.sock = object()

        def getresponse(self):
            return responses.pop(0)

        def close(self):
            self.sock = None

    monkeypatch.setattr(http.client, "HTTPSConnection", FakeConn)

    key = "sb_secret_abc"
    b = backends.HttpBackend("https://example.supabase.co", key)
    responses.append(FakeResp(200, json.dumps('[{"rows":[{"a":1,"a":2}]},{"rowcount":3}]')))
    assert b.execute_batch(["select 1 as a, 2 as a", "update x set y=1"], "financehub") == [
        {"columns": ["a", "a"], "rows": [[1, 2]]}, {"rowcount": 3}]
    method, url, body, headers = sent[-1]
    assert (method, url) == ("POST", "/rest/v1/rpc/fh_exec")
    assert body == {"stmts": ["select 1 as a, 2 as a", "update x set y=1"], "schema": "financehub"}
    assert headers["apikey"] == key and "Authorization" not in headers
    assert headers["Content-Type"] == "application/json"

    jwt = "eyJhbGciOi.fake"
    b2 = backends.HttpBackend("https://example.supabase.co", jwt)
    for status, code, cls in [(409, "23505", IntegrityError), (400, "42P01", ProgrammingError),
                              (500, "57014", OperationalError), (503, "PGRST000", OperationalError)]:
        responses.append(FakeResp(status, json.dumps({"code": code, "message": "boom"})))
        with pytest.raises(cls) as ei:
            b2.execute_batch(["select 1"], "financehub")
        assert code in str(ei.value) and jwt not in str(ei.value)
    assert sent[-1][3]["Authorization"] == f"Bearer {jwt}"


