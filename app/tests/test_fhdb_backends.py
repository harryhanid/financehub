"""Test fhdb.backends. Backend lokal (PgBackend) selalu jalan; kontrak HttpBackend ke Supabase
(marker contract_http) hanya kalau FH_CONTRACT_HTTP=1:

    FH_CONTRACT_HTTP=1 FH_CONTRACT_SCHEMA=financehub_test python -m pytest tests/test_fhdb_backends.py -m contract_http -q

Kredensial HTTP: env SUPABASE_URL + SUPABASE_SERVICE_KEY, atau app/.env.
"""
import os
import socket

import pytest

from fhdb.errors import IntegrityError, OperationalError, ProgrammingError

CONTRACT_HTTP = os.environ.get("FH_CONTRACT_HTTP") == "1"
HTTP_SCHEMA = os.environ.get("FH_CONTRACT_SCHEMA", "financehub_test")

_T_DDL = ('create table if not exists t (id bigint generated by default as identity primary key, '
          '"Nama" text not null, jumlah double precision)')


def _http_credentials():
    url, key = os.environ.get("SUPABASE_URL"), os.environ.get("SUPABASE_SERVICE_KEY")
    if not (url and key):
        from dotenv import dotenv_values
        env = dotenv_values(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), ".env"))
        url, key = url or env.get("SUPABASE_URL"), key or env.get("SUPABASE_SERVICE_KEY")
    if not (url and key):
        pytest.fail("SUPABASE_URL / SUPABASE_SERVICE_KEY tidak ditemukan untuk kontrak HTTP")
    return url, key


@pytest.fixture(params=[
    "pg",
    pytest.param("http", marks=[
        pytest.mark.contract_http,
        pytest.mark.skipif(not CONTRACT_HTTP, reason="set FH_CONTRACT_HTTP=1 untuk kontrak HTTP"),
    ]),
])
def backend(request):
    """(backend, schema) dengan tabel t kosong."""
    if request.param == "pg":
        b, schema = request.getfixturevalue("pg_backend"), "financehub_test"
    else:
        from fhdb.backends import HttpBackend
        b, schema = HttpBackend(*_http_credentials()), HTTP_SCHEMA
        b.execute_batch([_T_DDL], schema)
    b.execute_batch(["truncate t restart identity"], schema)
    yield b, schema
    if request.param == "http":
        b.close()


