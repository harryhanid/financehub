"""Fixture Postgres bersama untuk test fhdb (didaftarkan dari conftest.py lewat pytest_plugins).

- `pg_dsn` (session): server Postgres lokal (tests/_pg) di port 54330, data dir di tmp session,
  `db_migrations/0001_fh_exec.sql` diterapkan, schema `financehub_test` + tabel `t` dibuat.
- `pg_backend` (function): `fhdb.backends.PgBackend` ke server itu, ditutup setelah test.
"""
import os

import pytest

PG_TEST_PORT = 54330  # test_local_pg.py memakai 54331
TEST_SCHEMA = "financehub_test"
MIGRATIONS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "db_migrations")


@pytest.fixture(scope="session")
def pg_dsn(tmp_path_factory):
    import psycopg2
    from tests.pgtest import local_pg

    data_dir = str(tmp_path_factory.mktemp("fhdb_pg") / "pgdata")
    dsn = local_pg.start(data_dir, port=PG_TEST_PORT)
    try:
        with open(os.path.join(MIGRATIONS_DIR, "0001_fh_exec.sql"), encoding="utf-8") as f:
            fh_exec_sql = f.read()
        conn = psycopg2.connect(dsn)
        try:
            conn.autocommit = True
            with conn.cursor() as cur:
                cur.execute(fh_exec_sql)
                cur.execute(f"create schema if not exists {TEST_SCHEMA}")
                cur.execute(
                    f'create table if not exists {TEST_SCHEMA}.t ('
                    'id bigint generated by default as identity primary key, '
                    '"Nama" text not null, '
                    'jumlah double precision)'
                )
        finally:
            conn.close()
        yield dsn
    finally:
        local_pg.stop(data_dir)


@pytest.fixture
def pg_backend(pg_dsn):
    from fhdb.backends import PgBackend

    backend = PgBackend(pg_dsn)
    try:
        yield backend
    finally:
        backend.close()
