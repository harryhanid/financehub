"""Generate a faithful Postgres schema from a SQLite database (read-only).

Usage: python scripts/pg_migrate/generate_schema.py <path-to-db> > app/db_migrations/0002_schema.sql

Output SQL uses the placeholder ``{{schema}}`` (substituted by apply_migrations.py).

Rules:
- Every identifier is quoted exactly as in SQLite (mixed case, '-').
- Types: TEXT -> text collate "C" (R28, byte order seperti SQLite BINARY), INTEGER -> bigint, REAL -> double precision; untyped -> from data kinds.
  If the declared type's mapping would lose values present in the data (INTEGER holding reals,
  INTEGER/REAL holding non-numeric text), the column falls back to a type that holds all observed
  values (double precision, else text). Each override is listed in a comment at the top.
- ``INTEGER PRIMARY KEY [AUTOINCREMENT]`` -> ``bigint generated by default as identity primary key``.
- ``DEFAULT CURRENT_TIMESTAMP`` -> text in the same format as SQLite (UTC 'YYYY-MM-DD HH:MM:SS').
- PRIMARY KEY / UNIQUE / CHECK / indexes are carried over. FOREIGN KEYs are added with ALTER TABLE at
  the end; an FK that has orphan rows in the data is created NOT VALID (data is never deleted).
- Views: known translations (``pa_summary``) or the original SELECT with table names qualified.
"""
import os
import re
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from profile_sqlite import profile  # noqa: E402

S = "{{schema}}"

# Translation of SQLite views. Source: C:/FinanceHub/scripts/sqlite_to_supabase.py (VIEWS),
# GROUP_CONCAT(DISTINCT x) -> string_agg(DISTINCT x::text, ','); original column names kept.
VIEWS = {
    "pa_summary": f"""create view {S}."pa_summary" as
select
    e."company_id",
    e."pa_number",
    string_agg(distinct e."tgl_payment_application"::text, ',') as "tgl_payment_application",
    string_agg(distinct e."nomor_pam"::text, ',')               as "nomor_pam",
    string_agg(distinct s."nama"::text, ',')                    as "nama_student",
    string_agg(distinct l."jenis_pembayaran"::text, ',')        as "jenis_pembayaran",
    string_agg(distinct l."semester"::text, ',')                as "semester",
    sum(l."jumlah_pembayaran")                                  as "jumlah_pembayaran",
    string_agg(distinct e."status"::text, ',')                  as "status",
    string_agg(distinct e."tanggal_bayar"::text, ',')           as "tanggal_bayar",
    string_agg(distinct e."keterangan"::text, ',')              as "keterangan"
from {S}."etf_pa" e
left join {S}."etf_pa_lines" l on l."pa_id" = e."id"
left join {S}."siswa" s on s."id" = l."student_id"
group by e."company_id", e."pa_number\"""",
}

_SQLITE_ONLY_FUNCS = re.compile(r"\b(group_concat|strftime|datetime|julianday|ifnull|printf|instr)\s*\(", re.I)
_NUM_RE = re.compile(r"^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$")
_TS_DEFAULTS = {
    "CURRENT_TIMESTAMP": "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')",
    "CURRENT_DATE": "to_char(now() at time zone 'utc', 'YYYY-MM-DD')",
    "CURRENT_TIME": "to_char(now() at time zone 'utc', 'HH24:MI:SS')",
}


def q(name):
    return '"' + name.replace('"', '""') + '"'


def _affinity(declared):
    """SQLite type affinity (https://sqlite.org/datatype3.html, 3.1)."""
    d = (declared or "").upper()
    if "INT" in d:
        return "integer"
    if any(k in d for k in ("CHAR", "CLOB", "TEXT")):
        return "text"
    if d == "" or "BLOB" in d:
        return "blob"
    if any(k in d for k in ("REAL", "FLOA", "DOUB")):
        return "real"
    return "numeric"


def pg_type(declared, kinds):
    """-> (pg_type, override_reason | None). `kinds` = sqlite typeof counts from profile()."""
    present = {k for k, n in kinds.items() if n and k != "null"}
    if "blob" in present:
        raise ValueError(f"kolom bertipe {declared!r} berisi blob: tidak didukung, tangani manual")
    aff = _affinity(declared)
    if aff == "integer":
        base = "bigint"
    elif aff in ("real", "numeric"):
        base = "double precision"
    elif aff == "text":
        base = "text"
    else:  # untyped: type that holds all observed values (majority when only one kind)
        if not present or "text" in present:
            return "text", None
        return ("bigint" if present == {"integer"} else "double precision"), None
    if base == "bigint" and "text" in present:
        return "text", f"deklarasi {declared}, berisi teks non-numerik {kinds.get('text')}x"
    if base == "bigint" and "real" in present:
        return "double precision", f"deklarasi {declared}, berisi nilai real {kinds.get('real')}x"
    if base == "double precision" and "text" in present:
        return "text", f"deklarasi {declared}, berisi teks non-numerik {kinds.get('text')}x"
    return base, None


def pg_default(raw, typ):
    if raw is None:
        return None
    v = raw.strip()
    while v.startswith("(") and v.endswith(")"):
        v = v[1:-1].strip()
    up = v.upper()
    if up in _TS_DEFAULTS:
        return _TS_DEFAULTS[up]
    if up == "NULL":
        return "null"
    if up in ("TRUE", "FALSE"):  # SQLite stores booleans as 1/0
        v = "1" if up == "TRUE" else "0"
    if _NUM_RE.match(v):
        return v if typ != "text" else "'" + v + "'"
    if len(v) >= 2 and v[0] == "'" and v[-1] == "'":
        if typ == "text":
            return v
        inner = v[1:-1]
        if _NUM_RE.match(inner.strip()):
            return inner.strip()
        raise ValueError(f"default {raw!r} bukan angka untuk kolom {typ}")
    raise ValueError(f"default {raw!r} tidak didukung generator, tangani manual")


def _split_top(body):
    """Split at top-level commas, respecting quotes and parentheses."""
    parts, depth, cur, i, n = [], 0, [], 0, len(body)
    while i < n:
        c = body[i]
        if c in "'\"`[":
            end = {"'": "'", '"': '"', "`": "`", "[": "]"}[c]
            j = i + 1
            while j < n:
                if body[j] == end:
                    if end != "]" and j + 1 < n and body[j + 1] == end:
                        j += 2
                        continue
                    break
                j += 1
            cur.append(body[i:j + 1])
            i = j + 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


def _strip_comments(sql):
    sql = re.sub(r"--[^\n]*", " ", sql)
    return re.sub(r"/\*.*?\*/", " ", sql, flags=re.S)


def _checks(create_sql):
    """CHECK expressions (column- and table-level) from a CREATE TABLE statement."""
    sql = _strip_comments(create_sql)
    body = sql[sql.index("(") + 1: sql.rindex(")")]
    out = []
    for part in _split_top(body):
        # walk the part at depth 0 (outside quotes) looking for CHECK (
        i, n, depth = 0, len(part), 0
        while i < n:
            c = part[i]
            if c in "'\"`[":
                end = "]" if c == "[" else c
                j = part.find(end, i + 1)
                i = n if j == -1 else j + 1
                continue
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif depth == 0 and part[i:i + 5].upper() == "CHECK" and (i == 0 or not part[i - 1].isalnum()):
                k = i + 5
                while k < n and part[k].isspace():
                    k += 1
                if k < n and part[k] == "(":
                    d, m = 0, k
                    while m < n:
                        if part[m] == "(":
                            d += 1
                        elif part[m] == ")":
                            d -= 1
                            if d == 0:
                                break
                        elif part[m] == "'":
                            m = part.index("'", m + 1)
                        m += 1
                    out.append(part[k + 1:m].strip())
                    i = m + 1
                    continue
            i += 1
    return out


def _qualify_view(name, sql):
    if _SQLITE_ONLY_FUNCS.search(sql):
        raise ValueError(f"view {name}: memakai fungsi khusus SQLite, tambahkan terjemahan ke VIEWS")
    m = re.search(r"\bas\b(.*)$", _strip_comments(sql), re.I | re.S)
    select = m.group(1).strip()

    def repl(mo):
        ident = mo.group(2)
        if ident.startswith('"'):
            ident = ident[1:-1].replace('""', '"')
        return f"{mo.group(1)} {S}.{q(ident)}"

    select = re.sub(r'\b(from|join)\s+("(?:[^"]|"")+"|[A-Za-z_][\w]*)', repl, select, flags=re.I)
    return f"create view {S}.{q(name)} as\n{select}"


def generate(db_path: str) -> str:
    prof = profile(db_path)
    uri = "file:" + db_path.replace("\\", "/") + "?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    try:
        return _generate(conn, prof)
    finally:
        conn.close()


def _generate(conn, prof):
    objects = conn.execute(
        "select type, name, sql from sqlite_master where type in ('table', 'view') "
        "and name not like 'sqlite_%' order by rowid").fetchall()
    tables = [(n, s) for t, n, s in objects if t == "table"]
    views = [(n, s) for t, n, s in objects if t == "view"]

    overrides, col_types, pk_cols = [], {}, {}
    table_sql, index_sql, fk_sql, fk_notes = [], [], [], []

    for tname, create_sql in tables:
        if re.search(r"\bwithout\s+rowid\b", create_sql, re.I):
            raise ValueError(f"tabel {tname}: WITHOUT ROWID tidak didukung")
        info = conn.execute(f"pragma table_info({q(tname)})").fetchall()
        pks = sorted((c for c in info if c[5]), key=lambda c: c[5])
        pk_cols[tname] = [c[1] for c in pks]
        identity = len(pks) == 1 and (pks[0][2] or "").upper() == "INTEGER"
        lines = []
        types = {}
        for _cid, cname, declared, notnull, dflt, pk in info:
            if identity and pk:
                types[cname] = "bigint"
                lines.append(f"    {q(cname)} bigint generated by default as identity primary key")
                continue
            typ, why = pg_type(declared, prof[tname][cname]["kinds"])
            if why:
                overrides.append(f"{tname}.{cname}: {typ} ({why})")
            types[cname] = typ
            line = f"    {q(cname)} {typ}"
            if typ == "text":
                line += ' collate "C"'  # R28: urutan byte seperti BINARY di SQLite
            if notnull or pk:
                line += " not null"
            d = pg_default(dflt, typ)
            if d is not None:
                line += f" default {d}"
            lines.append(line)
        col_types[tname] = types
        if pks and not identity:
            lines.append(f"    primary key ({', '.join(q(c[1]) for c in pks)})")
        for il in conn.execute(f"pragma index_list({q(tname)})").fetchall():
            _seq, iname, unique, origin, partial = il[:5]
            cols = [r for r in conn.execute(f"pragma index_xinfo({q(iname)})").fetchall() if r[5]]
            if any(r[2] is None for r in cols):
                raise ValueError(f"index {iname}: index ekspresi tidak didukung")
            if origin == "pk":
                continue
            if origin == "u":
                lines.append(f"    unique ({', '.join(q(r[2]) for r in cols)})")
                continue
            if partial:
                raise ValueError(f"index {iname}: partial index tidak didukung")
            colspec = ", ".join(q(r[2]) + (" desc" if r[3] else "") for r in cols)
            index_sql.append(
                f"create {'unique ' if unique else ''}index {q(iname)} on {S}.{q(tname)} ({colspec});")
        for expr in _checks(create_sql):
            lines.append(f"    check ({expr})")
        table_sql.append(f"create table {S}.{q(tname)} (\n" + ",\n".join(lines) + "\n);")

    for tname, _sql in tables:
        groups = {}
        for fid, seq, parent, frm, to, on_upd, on_del, _match in conn.execute(
                f"pragma foreign_key_list({q(tname)})").fetchall():
            groups.setdefault(fid, {"parent": parent, "pairs": [], "upd": on_upd, "del": on_del})
            groups[fid]["pairs"].append((seq, frm, to))
        for fid in sorted(groups):
            g = groups[fid]
            parent = g["parent"]
            pairs = sorted(g["pairs"])
            child = [p[1] for p in pairs]
            par = [p[2] for p in pairs]
            if any(p is None for p in par):
                par = pk_cols[parent]
            for c, p in zip(child, par):
                ct, pt = col_types[tname][c], col_types[parent][p]
                if ct != pt:
                    raise ValueError(f"FK {tname}.{c} ({ct}) -> {parent}.{p} ({pt}): tipe tidak cocok")
            cond = " and ".join(f"p.{q(p)} = c.{q(c)}" for c, p in zip(child, par))
            notnull = " and ".join(f"c.{q(c)} is not null" for c in child)
            orphans = conn.execute(
                f"select count(*) from {q(tname)} c where {notnull} and not exists "
                f"(select 1 from {q(parent)} p where {cond})").fetchone()[0]
            stmt = (f"alter table {S}.{q(tname)} add foreign key ({', '.join(q(c) for c in child)}) "
                    f"references {S}.{q(parent)} ({', '.join(q(p) for p in par)})")
            if g["del"] and g["del"] != "NO ACTION":
                stmt += f" on delete {g['del'].lower()}"
            if g["upd"] and g["upd"] != "NO ACTION":
                stmt += f" on update {g['upd'].lower()}"
            if orphans:
                stmt += " not valid"
                fk_notes.append(f"{tname}({', '.join(child)}) -> {parent}: {orphans} baris orphan, FK NOT VALID")
            fk_sql.append(stmt + ";")

    view_sql = []
    for vname, vsql in views:
        view_sql.append((VIEWS[vname] if vname in VIEWS else _qualify_view(vname, vsql)) + ";")

    out = ["-- 0002_schema.sql -- DIHASILKAN oleh scripts/pg_migrate/generate_schema.py, jangan edit manual.",
           "-- Placeholder {{schema}} diganti oleh scripts/pg_migrate/apply_migrations.py.",
           f"-- {len(tables)} tabel, {len(view_sql)} view, {len(index_sql)} index, {len(fk_sql)} foreign key.",
           "--",
           "-- Override tipe (tipe deklarasi akan memotong/menolak nilai yang ada di data):"]
    out += [f"--   {o}" for o in overrides] or ["--   (tidak ada)"]
    out += ["--", "-- Foreign key NOT VALID (ada baris orphan di SQLite; data tidak dihapus):"]
    out += [f"--   {n}" for n in fk_notes] or ["--   (tidak ada)"]
    out += ["", "-- Tabel", ""]
    out += [t + "\n" for t in table_sql]
    out += ["-- Index", ""] + index_sql
    out += ["", "-- Foreign key", ""] + fk_sql
    out += ["", "-- View", ""] + view_sql
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stdout.write(generate(sys.argv[1]))
