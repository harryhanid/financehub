"""General Ledger: table storage, sync log and viewer queries."""
import json
from datetime import datetime

from database import get_conn
from modules.general_ledger import staging
from modules.general_ledger.parser import COLUMNS

ENTITIES = {
    "smt":  {"sheet": "GL SMT",  "table": "GLSMT",  "label": "GL SMT"},
    "etf":  {"sheet": "GL ETF",  "table": "GLETF",  "label": "GL ETF"},
    "setf": {"sheet": "GL SETF", "table": "GLSETF", "label": "GL SETF"},
}

_REAL = {"debit", "credit", "qty_awal", "qty_akhir", "harga_satuan", "debit_credit"}
_INT = {"entry_no"}


def _q(name: str) -> str:
    return '"' + name + '"'      # GLSMT etc. are upper case: unquoted they fold to lower case in Postgres


def _col_type(c):
    # Same types as 0002_schema.sql (REAL -> double precision, INTEGER -> bigint, TEXT -> text "C").
    return "double precision" if c in _REAL else "bigint" if c in _INT else 'text collate "C"'


def _table_ddl(table) -> list:
    cols = ",\n    ".join(f"{_q(c)} {_col_type(c)}" for c in COLUMNS)
    return [f"CREATE TABLE IF NOT EXISTS {_q(table)} (\n    \"id\" bigint generated by default as identity "
            f"primary key,\n    {cols}\n)",
            f"CREATE INDEX IF NOT EXISTS {_q('idx_' + table + '_tgl')} ON {_q(table)} (\"tgl\")",
            f"CREATE INDEX IF NOT EXISTS {_q('idx_' + table + '_acc')} ON {_q(table)} (\"acc_statutory\")",
            f"ALTER TABLE {_q(table)} ENABLE ROW LEVEL SECURITY"]          # R19


_LOG_DDL = [
    """CREATE TABLE IF NOT EXISTS "gl_sync_log" (
    "id"           bigint generated by default as identity primary key,
    "entity"       text collate "C" NOT NULL,
    "year"         bigint,
    "synced_at"    text collate "C",
    "synced_by"    text collate "C",
    "filename"     text collate "C",
    "content_hash" text collate "C",
    "rows_before"  bigint DEFAULT 0,
    "rows_after"   bigint DEFAULT 0,
    "total_debit"  double precision DEFAULT 0,
    "total_credit" double precision DEFAULT 0,
    "dropped"      bigint DEFAULT 0,
    "summary"      text collate "C"
)""",
    'CREATE INDEX IF NOT EXISTS "idx_gl_sync_log_entity" ON "gl_sync_log" ("entity", "id")',
]
_LOG_RLS = 'ALTER TABLE "gl_sync_log" ENABLE ROW LEVEL SECURITY'


def _index_names():
    names = ["idx_gl_sync_log_entity"]
    for ent in ENTITIES.values():
        names += [f"idx_{ent['table']}_tgl", f"idx_{ent['table']}_acc"]
    return names


def ensure_schema(conn) -> None:
    """Create / repair the per-entity GL tables and gl_sync_log.

    All reads first (one call), then every DDL in ONE batch: a failure never leaves a table renamed
    to _legacy without its replacement. On a migrated database (0002_schema.sql) nothing is written."""
    expected = {"id", *COLUMNS}
    tables = [ent["table"] for ent in ENTITIES.values()]
    idx = _index_names()
    reads = [(f"PRAGMA table_info({t})", ()) for t in tables] + [
        ("PRAGMA table_info(gl_sync_log)", ()),
        ("SELECT count(*) FROM pg_indexes WHERE schemaname = current_schema() AND indexname IN ("
         + ",".join("?" * len(idx)) + ")", idx)]
    curs = conn.batch(reads)
    stmts, rebuilt = [], set()
    for table, cur in zip(tables, curs):
        existing = {r[1] for r in cur}
        if existing == expected:
            continue
        if existing:
            # Old pandas to_sql layout (or an older COLUMNS set): keep the data aside, never drop it.
            legacy = f"{table}_legacy"
            stmts += [f"DROP TABLE IF EXISTS {_q(legacy)}",
                      f"DROP INDEX IF EXISTS {_q('idx_' + table + '_tgl')}",
                      f"DROP INDEX IF EXISTS {_q('idx_' + table + '_acc')}",
                      f"ALTER TABLE {_q(table)} RENAME TO {_q(legacy)}"]
        stmts += _table_ddl(table)
        rebuilt.add(table)
    log_cols = {r[1] for r in curs[len(tables)]}
    if not log_cols:
        stmts += _LOG_DDL + [_LOG_RLS]
    elif "year" not in log_cols:
        stmts.append('ALTER TABLE "gl_sync_log" ADD COLUMN "year" bigint')   # logs before multi-year stay NULL
    if curs[-1].fetchone()[0] != len(idx):          # an index is missing: CREATE INDEX IF NOT EXISTS
        stmts += [s for t in tables if t not in rebuilt for s in _table_ddl(t)[1:3]] + _LOG_DDL[1:]
    if stmts:
        conn.batch([(s, ()) for s in stmts])


def _ts() -> str:
    return datetime.now().isoformat(timespec="seconds")


def _year_of(tgl):
    return str(tgl)[:4] if tgl else ""


def replace_year(entity, year, rows, log) -> None:
    """Replace only the rows dated in `year`; every other year stays untouched.

    R21: rows go to a per-run staging table in chunks, then ONE batch deletes the year, copies the
    staged rows (in sheet order), writes gl_sync_log and drops the staging table: all or nothing."""
    year = int(year)
    if any(_year_of(r["tgl"]) != str(year) for r in rows):
        raise ValueError(f"Semua baris harus bertanggal {year}.")
    table = ENTITIES[entity]["table"]
    values = [tuple(r[c] for c in COLUMNS) for r in rows]        # KeyError on a bad row: nothing written
    log_params = (entity, year, _ts(), log["synced_by"], log["filename"], log["content_hash"],
                  log["rows_before"], log["rows_after"], log["total_debit"], log["total_credit"],
                  log["dropped"], json.dumps(log["summary"], ensure_ascii=False))
    conn = get_conn()
    stage = staging.new_name("gl")
    try:
        ensure_schema(conn)
        staging.drop_orphans(conn, "gl")
        staging.create(conn, stage, [(c, _col_type(c)) for c in COLUMNS])
        try:
            n = staging.load(conn, stage, COLUMNS, values)
            conn.batch([
                staging.guard(stage, n),
                (f"DELETE FROM {_q(table)} WHERE substr(tgl,1,4) = ?", (str(year),)),
                staging.copy(table, stage, COLUMNS),
                ("INSERT INTO gl_sync_log (entity, year, synced_at, synced_by, filename, content_hash, "
                 "rows_before, rows_after, total_debit, total_credit, dropped, summary) "
                 "VALUES (?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id", log_params),
                staging.drop(stage),
            ])
        except Exception:
            staging.discard(conn, stage)
            raise
    finally:
        conn.close()


def _year_where(year):
    return ("", []) if year is None else (" WHERE substr(tgl,1,4) = ?", [str(int(year))])


def years_with_data(entity) -> list:
    """Years that hold at least one row, newest first."""
    table = ENTITIES[entity]["table"]
    conn = get_conn()
    try:
        ensure_schema(conn)
        cur = conn.execute(f"SELECT DISTINCT substr(tgl,1,4) FROM {_q(table)} "
                           f"WHERE tgl IS NOT NULL AND tgl <> '' ORDER BY 1 DESC")
        return [int(r[0]) for r in cur if str(r[0]).isdigit()]
    finally:
        conn.close()


def latest_year(entity):
    years = years_with_data(entity)
    return years[0] if years else None


def row_count(entity, year=None) -> int:
    table = ENTITIES[entity]["table"]
    where, params = _year_where(year)
    conn = get_conn()
    try:
        ensure_schema(conn)
        return conn.execute(f"SELECT COUNT(*) FROM {_q(table)}{where}", params).fetchone()[0]
    finally:
        conn.close()


def load_rows(entity, year=None) -> list:
    table = ENTITIES[entity]["table"]
    where, params = _year_where(year)
    conn = get_conn()
    try:
        ensure_schema(conn)
        return [dict(r) for r in conn.execute(
            f"SELECT {','.join(COLUMNS)} FROM {_q(table)}{where} ORDER BY id", params)]
    finally:
        conn.close()


def _log_row(r):
    d = dict(r)
    d["summary"] = json.loads(d["summary"]) if d.get("summary") else {}
    return d


def list_syncs(entity, year=None, limit=10) -> list:
    clause, params = ("", [])
    if year is not None:
        clause, params = (" AND year = ?", [int(year)])
    conn = get_conn()
    try:
        ensure_schema(conn)
        cur = conn.execute(f"SELECT * FROM gl_sync_log WHERE entity=?{clause} ORDER BY id DESC LIMIT ?",
                           [entity, *params, limit])
        return [_log_row(r) for r in cur]
    finally:
        conn.close()


def last_sync(entity, year=None):
    rows = list_syncs(entity, year, 1)
    return rows[0] if rows else None


def _like(text: str) -> str:
    esc = text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
    return f"%{esc}%"


def _where(filters: dict):
    clauses, params = [], []
    if filters.get("year"):
        clauses.append("substr(tgl,1,4) = ?")
        params.append(str(int(filters["year"])))
    if filters.get("date_from"):
        clauses.append("tgl >= ?")
        params.append(filters["date_from"])
    if filters.get("date_to"):
        clauses.append("tgl <= ?")
        params.append(filters["date_to"])
    if filters.get("acc"):
        clauses.append("(acc_statutory ILIKE ? ESCAPE '\\' OR acc_management ILIKE ? ESCAPE '\\' "
                       "OR acc_statutory_desc ILIKE ? ESCAPE '\\' OR acc_management_desc ILIKE ? ESCAPE '\\')")
        params += [_like(filters["acc"])] * 4
    if filters.get("job"):
        clauses.append("job_name ILIKE ? ESCAPE '\\'")
        params.append(_like(filters["job"]))
    if filters.get("q"):
        clauses.append("(memo ILIKE ? ESCAPE '\\' OR id_no ILIKE ? ESCAPE '\\')")
        params += [_like(filters["q"])] * 2
    return (" WHERE " + " AND ".join(clauses)) if clauses else "", params


def query_rows(entity, filters, page=1, per_page=100) -> dict:
    table = ENTITIES[entity]["table"]
    where, params = _where(filters or {})
    conn = get_conn()
    try:
        ensure_schema(conn)
        total, sum_debit, sum_credit = conn.execute(
            f"SELECT COUNT(*), COALESCE(SUM(debit),0), COALESCE(SUM(credit),0) FROM {_q(table)}{where}",
            params).fetchone()
        pages = max(1, -(-total // per_page))
        page = min(max(1, page), pages)
        rows = [dict(r) for r in conn.execute(
            f"SELECT {','.join(COLUMNS)} FROM {_q(table)}{where} "
            f"ORDER BY entry_no NULLS FIRST, id LIMIT ? OFFSET ?", params + [per_page, (page - 1) * per_page])]
    finally:
        conn.close()
    return {"rows": rows, "total": total, "sum_debit": sum_debit, "sum_credit": sum_credit,
            "page": page, "pages": pages, "per_page": per_page}


def load_mr_source(entity, year=None) -> list:
    """GL rows with an amount, reduced to what the MR row builder needs. Year defaults to the latest."""
    year = latest_year(entity) if year is None else year
    if year is None:
        return []
    table = ENTITIES[entity]["table"]
    conn = get_conn()
    try:
        ensure_schema(conn)
        return [dict(r) for r in conn.execute(
            f"SELECT id_no, acc_management, tgl, allocation_memo, budget_activity, job_name, debit_credit "
            f"FROM {_q(table)} WHERE debit_credit IS NOT NULL AND debit_credit <> 0 "
            f"AND substr(tgl,1,4) = ? ORDER BY id", (str(int(year)),))]
    finally:
        conn.close()


def account_totals(entity, year) -> list:
    """Per statutory account: row count and net amount (debit_credit) for one year."""
    table = ENTITIES[entity]["table"]
    conn = get_conn()
    try:
        ensure_schema(conn)
        return [{"account": r[0], "n": r[1], "amount": r[2]} for r in conn.execute(
            f"SELECT acc_statutory, COUNT(*), COALESCE(SUM(debit_credit), 0) FROM {_q(table)} "
            f"WHERE substr(tgl,1,4) = ? GROUP BY acc_statutory ORDER BY acc_statutory NULLS FIRST",
            (str(int(year)),))]
    finally:
        conn.close()


def load_lines(entity, year) -> list:
    """Every row of one year with its database id and the columns SPT Badan classifies."""
    table = ENTITIES[entity]["table"]
    conn = get_conn()
    try:
        ensure_schema(conn)
        return [dict(r) for r in conn.execute(
            f"SELECT id, tgl, id_no, acc_statutory, acc_management, job_name, memo, debit, credit, "
            f"debit_credit, category_lk, category_spt, pph_non_pph, accrual_actual FROM {_q(table)} "
            f"WHERE substr(tgl,1,4) = ? ORDER BY id", (str(int(year)),))]
    finally:
        conn.close()
