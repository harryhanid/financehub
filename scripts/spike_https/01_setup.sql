create schema if not exists fh_spike;

create table if not exists fh_spike.t (
    id     bigint generated by default as identity primary key,
    nama   text not null,
    jumlah double precision,
    tgl    text
);

-- Menjalankan daftar statement SQL dalam SATU transaksi (satu panggilan REST = satu transaksi).
-- Statement SELECT/WITH atau yang ber-RETURNING mengembalikan baris; lainnya mengembalikan rowcount.
-- Kalau satu statement error, seluruh daftar dibatalkan.
create or replace function public.fh_spike_exec(stmts jsonb)
returns jsonb
language plpgsql
as $$
declare
    s   text;
    res jsonb := '[]'::jsonb;
    r   jsonb;
    n   bigint;
begin
    for s in select jsonb_array_elements_text(stmts) loop
        if s ~* '^\s*(select|with)\M' or s ~* '\mreturning\M' then
            execute format(
                'with _q as (%s) select coalesce(jsonb_agg(to_jsonb(_q)), ''[]''::jsonb) from _q', s
            ) into r;
            res := res || jsonb_build_array(jsonb_build_object('rows', r));
        else
            execute s;
            get diagnostics n = row_count;
            res := res || jsonb_build_array(jsonb_build_object('rowcount', n));
        end if;
    end loop;
    return res;
end
$$;

-- Hanya service key yang boleh memanggil; anon/authenticated tidak.
revoke all on function public.fh_spike_exec(jsonb) from public, anon, authenticated;
grant execute on function public.fh_spike_exec(jsonb) to service_role;

notify pgrst, 'reload schema';
