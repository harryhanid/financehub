import importlib.util
import sqlite3
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
PG_MIGRATE = ROOT / "scripts" / "pg_migrate"
SCHEMA = "financehub_test"


def _load_mod(name):
    spec = importlib.util.spec_from_file_location(name, PG_MIGRATE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


load_data = _load_mod("load_data")
verify_mod = _load_mod("verify")
load = load_data.load
verify = verify_mod.verify

# Tabel kecil khusus test (dibuat di financehub_test, di-drop saat teardown). refresh_tokens sudah
# ada di skema lengkap (fhdb_schema) dan harus dilewati loader.
PG_TABLES = [
    'create table pb (id bigint generated by default as identity primary key, '
    'company_id bigint, jumlah double precision, catatan text, dpp double precision)',
    'create table ld_child (id bigint generated by default as identity primary key, '
    'pb_id bigint references pb (id), nilai bigint, ket text)',
]


def _make_sqlite(path, child_rows=None, pb_rows=None):
    c = sqlite3.connect(path)
    c.executescript(
        "create table pb (id integer primary key autoincrement, company_id integer, jumlah real, catatan text, dpp real);"
        "create table ld_child (id integer primary key autoincrement, pb_id integer references pb(id), "
        "nilai integer, ket);"
        "create table refresh_tokens (id integer primary key autoincrement, user_id integer, token text);"
    )
    c.executemany("insert into pb (id, company_id, jumlah, catatan) values (?,?,?,?)", pb_rows or [
        (1, 1, 1000.25, "a'b"), (2, 1, 0.1, None), (3, 2, 2500000.75, "x\\y"),
    ])
    # Kolom ket tanpa afinitas: INTEGER/REAL tersimpan apa adanya, target-nya text.
    c.executemany("insert into ld_child values (?,?,?,?)", child_rows or [
        (1, 1, 500, 5), (2, 3, "7", 1.5), (5, None, None, "teks"),
    ])
    c.executemany("insert into refresh_tokens values (?,?,?)", [(1, 999, "t1"), (2, 998, "t2")])
    c.commit()
    c.close()
    return str(path)


@pytest.fixture
def small(tmp_path, pg_backend):
    pg_backend.execute_batch(["drop table if exists ld_child", "drop table if exists pb"] + PG_TABLES, SCHEMA)
    try:
        yield tmp_path / "small.db"
    finally:
        pg_backend.execute_batch(["drop table if exists ld_child", "drop table if exists pb"], SCHEMA)


def _rows(backend, sql):
    return backend.execute_batch([sql], SCHEMA)[0]["rows"]


def test_load_then_verify_clean(small, pg_backend):
    db = _make_sqlite(small)
    counts = load(db, pg_backend, SCHEMA, chunk=2)
    assert "refresh_tokens" not in counts and counts["pb"] == 3 and counts["ld_child"] == 3
    assert verify(db, pg_backend, SCHEMA) == []
    nxt = pg_backend.execute_batch(['insert into pb (company_id) values (1) returning id'], SCHEMA)
    assert nxt[0]["rows"][0][0] == 4
    nxt = pg_backend.execute_batch(['insert into ld_child (nilai) values (1) returning id'], SCHEMA)
    assert nxt[0]["rows"][0][0] == 6


def test_load_values_exact_and_converted(small, pg_backend):
    db = _make_sqlite(small)
    load(db, pg_backend, SCHEMA)
    assert _rows(pg_backend, "select id, company_id, jumlah, catatan from pb order by id") == [
        [1, 1, 1000.25, "a'b"], [2, 1, 0.1, None], [3, 2, 2500000.75, "x\\y"]]
    # '7' (text di kolom INTEGER) -> bigint 7; 5 / 1.5 (angka di kolom text) -> '5' / '1.5'
    assert _rows(pg_backend, "select id, pb_id, nilai, ket from ld_child order by id") == [
        [1, 1, 500, "5"], [2, 3, 7, "1.5"], [5, None, None, "teks"]]


